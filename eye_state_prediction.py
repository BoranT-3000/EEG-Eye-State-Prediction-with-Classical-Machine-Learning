"""## 28B. SHAP Explanation for Tree-Based Models

SHAP TreeExplainer supports most tree-based scikit-learn models as well as XGBoost, LightGBM and CatBoost. Therefore, it is suitable if the final selected model is Random Forest, Extra Trees, Gradient Boosting, XGBoost or LightGBM.
"""

def run_tree_shap_explanation(model, X_train, X_test, max_background=500, max_explain=300):
    """
    Runs SHAP explanation for tree-based models.

    For computational efficiency:
    - background data is sampled from training set
    - explanation data is sampled from test set
    """

    inner_model = get_inner_model(model)

    tree_model_names = [
        "DecisionTreeClassifier",
        "RandomForestClassifier",
        "ExtraTreesClassifier",
        "GradientBoostingClassifier",
        "HistGradientBoostingClassifier",
        "XGBClassifier",
        "LGBMClassifier"
    ]

    if inner_model.__class__.__name__ not in tree_model_names:
        print("Tree SHAP skipped because the final model is not a supported tree-based model.")
        print("Final model type:", inner_model.__class__.__name__)
        return None, None, None

    X_background = X_train.sample(
        n=min(max_background, len(X_train)),
        random_state=RANDOM_STATE
    )

    X_explain = X_test.sample(
        n=min(max_explain, len(X_test)),
        random_state=RANDOM_STATE
    )

    explainer = shap.TreeExplainer(inner_model)
    shap_values = explainer.shap_values(X_explain)

    return explainer, shap_values, X_explain


