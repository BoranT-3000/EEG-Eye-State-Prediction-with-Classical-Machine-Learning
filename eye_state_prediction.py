"""## 7. Segment IDs for Sequential EEG Labels

Windowing yaparken 0 ve 1 sınıflarını karıştırmamak için ardışık aynı etiketlerden segment oluşturuyoruz. Örneğin:

000000111100000

şu segmentlere ayrılır:

0-segment, 1-segment, 0-segment.

Pencereler sadece kendi segmentinin içinde üretilecek.
"""

def make_contiguous_label_groups(y):
    """
    Creates group IDs for contiguous runs of the same class label.
    Example:
    y = [0,0,0,1,1,0,0]
    groups = [0,0,0,1,1,2,2]
    """
    y_series = pd.Series(y).reset_index(drop=True)
    groups = y_series.ne(y_series.shift()).cumsum() - 1
    return groups.to_numpy()


