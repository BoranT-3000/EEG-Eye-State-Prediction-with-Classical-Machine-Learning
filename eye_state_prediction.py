import optuna


def build_optuna_model(model_name: str, trial: optuna.Trial):
    """
    Builds a model with trial-suggested hyperparameters.
    """

    if model_name in ["KNN Uniform","KNN Distance","KNN Distance + RobustScaler"]:
        n_neighbors = trial.suggest_int("n_neighbors", 1, 31)
        p = trial.suggest_categorical("p", [1, 2])

        if model_name == "KNN Uniform":
            weights = "uniform"
        else:
            weights = "distance"

        if model_name == "KNN Distance + RobustScaler":
            scaler = RobustScaler()
        else:
            scaler = StandardScaler()

