"""## 21. Optuna Tuning Function"""

def tune_with_optuna(
    model_name: str,
    X,
    y,
    groups=None,
    cv_mode: str = "stratified",
    n_splits: int = 5,
    n_trials: int = 30
):
    if cv_mode == "group":
        if groups is None:
            raise ValueError("groups must be provided for group CV.")

        unique_groups = np.unique(groups)
        actual_splits = min(n_splits, len(unique_groups))
        cv = GroupKFold(n_splits=actual_splits)
        cv_groups = groups

    else:
        cv = StratifiedKFold(
            n_splits=n_splits,
            shuffle=True,
            random_state=RANDOM_STATE
        )
        cv_groups = None

    def objective(trial):
        model = build_optuna_model(model_name, trial)

        scores = cross_val_score(
            model,
            X,
            y,
            groups=cv_groups,
            cv=cv,
            scoring="accuracy",
            n_jobs=-1,
            error_score="raise"
        )

        return scores.mean()

    study = optuna.create_study(direction="maximize")
    study.optimize(objective, n_trials=n_trials, show_progress_bar=True)

    return study

