"""## 9. Window-Based Feature Extraction

Bu bölüm sinyali pencereleyip klasik ML’e uygun hale getirir. Model 3D sinyal almayacak; onun yerine her pencere için kanal bazlı istatistikler çıkarılacak.

Örnek:

14 kanal
11 özellik
toplam feature sayısı = 14 × 11 = 154
"""

def create_window_features(
    df_input: pd.DataFrame,
    feature_cols,
    target_col: str,
    window_size: int = 64,
    step_size: int = 16
):
    """
    Creates window-based tabular features from contiguous same-label EEG segments.

    Important:
    - Windows are created only inside homogeneous label segments.
    - No window contains both class 0 and class 1.
    - Each window is converted into statistical features.
    """

    X_values = df_input[feature_cols].to_numpy()
    y_values = df_input[target_col].to_numpy()

    segment_ids = make_contiguous_label_groups(y_values)

    rows = []
    labels = []
    groups = []

    feature_names = None

    for seg_id in np.unique(segment_ids):
        idx = np.where(segment_ids == seg_id)[0]

        if len(idx) < window_size:
            continue

        seg_X = X_values[idx]
        seg_y = y_values[idx]

        # Since this is a homogeneous segment, all labels are the same
        label = int(seg_y[0])

        for start in range(0, len(seg_X) - window_size + 1, step_size):
            window = seg_X[start:start + window_size]
            diff = np.diff(window, axis=0)

            blocks = {
                "mean": window.mean(axis=0),
                "std": window.std(axis=0),
                "min": window.min(axis=0),
                "max": window.max(axis=0),
                "median": np.median(window, axis=0),
                "q25": np.quantile(window, 0.25, axis=0),
                "q75": np.quantile(window, 0.75, axis=0),
                "rms": np.sqrt(np.mean(window ** 2, axis=0)),
                "ptp": np.ptp(window, axis=0),
                "diff_mean": diff.mean(axis=0),
                "diff_std": diff.std(axis=0),
                "simple_slope": (window[-1] - window[0]) / max(window_size - 1, 1)
            }

            if feature_names is None:
                feature_names = [
                    f"{channel}_{stat_name}"
                    for stat_name in blocks.keys()
                    for channel in feature_cols
                ]

            feature_vector = np.concatenate(list(blocks.values()))

            rows.append(feature_vector)
            labels.append(label)
            groups.append(seg_id)

    X_window = pd.DataFrame(rows, columns=feature_names)
    y_window = pd.Series(labels, name=target_col)
    groups_window = np.array(groups)

    return X_window, y_window, groups_window

