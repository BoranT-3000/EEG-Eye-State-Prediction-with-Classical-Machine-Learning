"""## 6. Robust Outlier Detection

Özgün çalışmada veri setinde birkaç iletim hatası / anormal değer olduğu belirtiliyor. Burada robust MAD tabanlı bir outlier kontrolü yapıyoruz.
"""

def detect_robust_outliers(X: pd.DataFrame, threshold: float = 12.0) -> pd.Series:
    """
    Detect row-level outliers using robust z-score based on median absolute deviation.
    A row is marked as outlier if any channel exceeds the threshold.
    """
    median = X.median(axis=0)
    mad = (X - median).abs().median(axis=0)

    # Avoid division by zero
    mad = mad.replace(0, np.nan)

    robust_z = 0.6745 * (X - median) / mad
    outlier_mask = robust_z.abs().gt(threshold).any(axis=1)

    return outlier_mask.fillna(False)


