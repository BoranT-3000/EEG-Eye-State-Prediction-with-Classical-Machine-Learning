"""## 13. Cross-Validation Comparison Function"""

def compare_models_cv(
    X,
    y,
    models: dict,
    groups=None,
    cv_mode: str = "stratified",
    n_splits: int = 5
):
    scoring = {
        "accuracy": "accuracy",
        "balanced_accuracy": "balanced_accuracy",
        "f1_macro": "f1_macro",
        "precision_macro": "precision_macro",
        "recall_macro": "recall_macro"
    }

    if cv_mode == "group":
        if groups is None:
            raise ValueError("groups must be provided when cv_mode='group'")

        unique_groups = np.unique(groups)
        actual_splits = min(n_splits, len(unique_groups))

        if actual_splits < 2:
            raise ValueError("Not enough groups for GroupKFold.")

        cv = GroupKFold(n_splits=actual_splits)
        cv_groups = groups

    elif cv_mode == "stratified":
        cv = StratifiedKFold(
            n_splits=n_splits,
            shuffle=True,
            random_state=RANDOM_STATE
        )
        cv_groups = None

    else:
        raise ValueError("cv_mode must be either 'stratified' or 'group'")

    results = []

    for name, model in models.items():
        print(f"Evaluating: {name}")

        try:
            scores = cross_validate(
                estimator=model,
                X=X,
                y=y,
                groups=cv_groups,
                cv=cv,
                scoring=scoring,
                n_jobs=-1,
                error_score=np.nan
            )

            row = {
                "model": name,
                "accuracy_mean": np.nanmean(scores["test_accuracy"]),
                "accuracy_std": np.nanstd(scores["test_accuracy"]),
                "balanced_accuracy_mean": np.nanmean(scores["test_balanced_accuracy"]),
                "f1_macro_mean": np.nanmean(scores["test_f1_macro"]),
                "precision_macro_mean": np.nanmean(scores["test_precision_macro"]),
                "recall_macro_mean": np.nanmean(scores["test_recall_macro"])
            }

        except Exception as e:
            row = {
                "model": name,
                "accuracy_mean": np.nan,
                "accuracy_std": np.nan,
                "balanced_accuracy_mean": np.nan,
                "f1_macro_mean": np.nan,
                "precision_macro_mean": np.nan,
                "recall_macro_mean": np.nan,
                "error": str(e)
            }

        results.append(row)

    results_df = pd.DataFrame(results)
    results_df = results_df.sort_values("accuracy_mean", ascending=False).reset_index(drop=True)

    return results_df

