"""## 29A. LIME Tabular Explainer

LIME is used for local model-agnostic explanations. Unlike SHAP TreeExplainer, it can explain KNN, SVC, Random Forest, XGBoost and most other classifiers as long as they provide predict_proba.
"""

def run_lime_explanation(model, X_train, X_test, y_test, sample_index=0):
    """
    Runs LIME explanation for one test sample.
    Works with any classifier that supports predict_proba.
    """

    if not hasattr(model, "predict_proba"):
        print("LIME skipped because the model does not support predict_proba.")
        return None

    class_names = ["Eye Open (0)", "Eye Closed (1)"]

    lime_explainer = lime.lime_tabular.LimeTabularExplainer(
        training_data=np.array(X_train),
        feature_names=list(X_train.columns),
        class_names=class_names,
        mode="classification",
        discretize_continuous=True,
        random_state=RANDOM_STATE
    )

    instance = X_test.iloc[sample_index].to_numpy()

    explanation = lime_explainer.explain_instance(
        data_row=instance,
        predict_fn=model.predict_proba,
        num_features=15
    )

    true_label = y_test.iloc[sample_index] if hasattr(y_test, "iloc") else y_test[sample_index]
    pred_label = model.predict(X_test.iloc[[sample_index]])[0]
    pred_proba = model.predict_proba(X_test.iloc[[sample_index]])[0]

    print("Sample index:", sample_index)
    print("True label:", true_label)
    print("Predicted label:", pred_label)
    print("Prediction probabilities:", pred_proba)

    return explanation


